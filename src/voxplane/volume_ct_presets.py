from voxplane.i18n import message as _msg
from voxplane.model.dicom_types import WindowLevel
from voxplane.model.volume_models import VolumePreset


def ct_preset(preset_id, group, window_range, colors, opacity, **lighting):
    """Normalize HU against the useful window, retaining outlying anchors.

    Sentinel points outside the window preserve the original tissue curves;
    using the full -3024..3071 extent as WW makes drags much too coarse.
    """
    low, high = window_range
    width = high-low
    return VolumePreset(
        preset_id, _msg("volume.preset."+preset_id), group,
        tuple(((hu-low)/width, r, g, b) for hu, r, g, b in colors),
        tuple(((hu-low)/width, alpha) for hu, alpha in opacity),
        default_window=WindowLevel((low+high)/2, width), ct_only=True, **lighting,
    )


